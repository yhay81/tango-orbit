import { createHash } from "node:crypto";
import { mkdtemp, readFile, readdir, rm, writeFile, mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import * as tar from "tar";

const RELEASE_API = "https://api.github.com/repos/scriptin/jmdict-simplified/releases/latest";
const PROJECT_ROOT = new URL("../", import.meta.url);
const PUBLIC_PATH = new URL("public/dictionary.json", PROJECT_ROOT);
const META_PATH = new URL("src/generated/dictionary.ts", PROJECT_ROOT);

const unique = (values) => [...new Set(values.filter(Boolean))];

function orderedForms(forms) {
  return unique(
    [...forms]
      .sort((left, right) => Number(right.common) - Number(left.common))
      .map((form) => form.text),
  );
}

function relationWords(relations) {
  return unique(relations.map((relation) => relation[0])).slice(0, 12);
}

function compactWord(word) {
  const senses = word.sense
    .map((sense) => ({
      g: unique(sense.gloss.filter((gloss) => gloss.lang === "eng").map((gloss) => gloss.text)),
      p: unique(sense.partOfSpeech),
      n: unique(sense.info),
    }))
    .filter((sense) => sense.g.length > 0);

  return {
    i: word.id,
    k: orderedForms(word.kanji),
    r: orderedForms(word.kana),
    s: senses,
    x: relationWords(word.sense.flatMap((sense) => sense.related)),
    a: relationWords(word.sense.flatMap((sense) => sense.antonym)),
  };
}

async function downloadLatest(tempDirectory) {
  const releaseResponse = await fetch(RELEASE_API, {
    headers: {
      Accept: "application/vnd.github+json",
      "User-Agent": "tango-orbit-dictionary-updater",
      "X-GitHub-Api-Version": "2022-11-28",
    },
  });
  if (!releaseResponse.ok) {
    throw new Error(`GitHub release lookup failed: ${releaseResponse.status}`);
  }

  const release = await releaseResponse.json();
  const asset = release.assets.find((item) => /^jmdict-eng-common-.+\.json\.tgz$/.test(item.name));
  if (!asset) {
    throw new Error("The latest release has no English common-only archive.");
  }

  const archiveResponse = await fetch(asset.browser_download_url, {
    headers: { "User-Agent": "tango-orbit-dictionary-updater" },
  });
  if (!archiveResponse.ok) {
    throw new Error(`Dictionary download failed: ${archiveResponse.status}`);
  }

  const bytes = Buffer.from(await archiveResponse.arrayBuffer());
  const actualDigest = `sha256:${createHash("sha256").update(bytes).digest("hex")}`;
  if (!asset.digest || actualDigest !== asset.digest.toLowerCase()) {
    throw new Error(
      `Dictionary checksum mismatch: expected ${asset.digest ?? "missing"}, got ${actualDigest}`,
    );
  }

  const archivePath = join(tempDirectory, asset.name);
  await writeFile(archivePath, bytes);
  await tar.x.asyncFile(
    {
      file: archivePath,
      cwd: tempDirectory,
      strict: true,
    },
    [],
  );

  const extractedName = (await readdir(tempDirectory)).find((name) =>
    /^jmdict-eng-common-.+\.json$/.test(name),
  );
  if (!extractedName) {
    throw new Error("The dictionary archive did not contain the expected JSON file.");
  }

  return {
    filePath: join(tempDirectory, extractedName),
    releaseTag: release.tag_name,
    assetName: asset.name,
    assetUrl: asset.browser_download_url,
    digest: actualDigest,
  };
}

async function main() {
  const tempDirectory = await mkdtemp(join(tmpdir(), "tango-orbit-jmdict-"));
  try {
    const source = await downloadLatest(tempDirectory);
    const original = JSON.parse(await readFile(source.filePath, "utf8"));
    const words = original.words.map(compactWord);
    const usedTags = unique(words.flatMap((word) => word.s.flatMap((sense) => sense.p))).sort(
      (left, right) => left.localeCompare(right),
    );
    const tags = Object.fromEntries(usedTags.map((tag) => [tag, original.tags[tag] ?? tag]));

    const output = {
      schema: 1,
      date: original.dictDate,
      release: source.releaseTag,
      entries: words.length,
      source: {
        name: "JMdict",
        owner: "Electronic Dictionary Research and Development Group",
        project: "https://www.edrdg.org/wiki/JMdict-EDICT_Dictionary_Project.html",
        licence: "https://creativecommons.org/licenses/by-sa/4.0/",
        archive: source.assetName,
        archiveUrl: source.assetUrl,
        digest: source.digest,
      },
      tags,
      words,
    };

    await mkdir(new URL("public/", PROJECT_ROOT), { recursive: true });
    await mkdir(new URL("src/generated/", PROJECT_ROOT), { recursive: true });
    await writeFile(PUBLIC_PATH, `${JSON.stringify(output)}\n`, "utf8");
    await writeFile(
      META_PATH,
      [
        "// Generated by scripts/update-dictionary.mjs. Do not edit by hand.",
        "export const DICTIONARY_META = {",
        `  date: ${JSON.stringify(output.date)},`,
        `  release: ${JSON.stringify(output.release)},`,
        `  entries: ${output.entries},`,
        `  archive: ${JSON.stringify(output.source.archive)},`,
        `  digest: ${JSON.stringify(output.source.digest)},`,
        "} as const;",
        "",
      ].join("\n"),
      "utf8",
    );

    const outputBytes = Buffer.byteLength(JSON.stringify(output));
    console.log(
      `Updated ${words.length.toLocaleString("en-US")} entries from ${source.releaseTag} (${outputBytes.toLocaleString("en-US")} bytes).`,
    );
  } finally {
    await rm(tempDirectory, { recursive: true, force: true });
  }
}

await main();
